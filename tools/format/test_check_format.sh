#!/bin/sh
# test_check_format.sh: verify check_format.sh passes the clean fixture, fails
# the dirty fixture with its name, reports the file count for a mixed run, and
# exits 2 when clang-format-18 is missing.
set -eu

ROOT="$(cd "$(dirname "$0")/../.." && pwd)"
SCRIPT="$ROOT/tools/format/check_format.sh"
cd "$ROOT" || exit 1
CLEAN="tools/format/testdata/clean.c"
DIRTY="tools/format/testdata/dirty.c"

mkdir -p "$ROOT/build"
tmp="$(mktemp -d "$ROOT/build/format-test.XXXXXX")"
trap 'rm -rf "$tmp"' EXIT

if ! sh "$SCRIPT" "$CLEAN" >"$tmp/clean.out" 2>&1; then
    echo "FAIL: check_format.sh did not pass clean.c" >&2
    exit 1
fi

set +e
sh "$SCRIPT" "$DIRTY" >"$tmp/dirty.out" 2>&1
rc=$?
set -e
if [ "$rc" -ne 1 ]; then
    echo "FAIL: dirty.c expected exit 1, got $rc" >&2
    exit 1
fi
if ! grep -qx "tools/format/testdata/dirty.c: not formatted" "$tmp/dirty.out"; then
    echo "FAIL: dirty.c output does not name the file" >&2
    exit 1
fi

set +e
sh "$SCRIPT" "$CLEAN" "$DIRTY" >"$tmp/both.out" 2>&1
rc=$?
set -e
if [ "$rc" -ne 1 ]; then
    echo "FAIL: mixed run expected exit 1, got $rc" >&2
    exit 1
fi
if ! grep -q "1 of 2 files not formatted" "$tmp/both.out"; then
    echo "FAIL: mixed run does not print 1 of 2 files not formatted" >&2
    exit 1
fi

set +e
CLANG_FORMAT=/nonexistent sh "$SCRIPT" "$CLEAN" >"$tmp/missing.out" 2>&1
rc=$?
set -e
if [ "$rc" -ne 2 ]; then
    echo "FAIL: missing clang-format expected exit 2, got $rc" >&2
    exit 1
fi
if ! grep -q "clang-format-18 not found" "$tmp/missing.out"; then
    echo "FAIL: missing clang-format message absent" >&2
    exit 1
fi

# the whole-tree mode: git cannot list -> exit 2, never "ok: 0 files"
set +e
GIT_DIR=/nonexistent sh "$SCRIPT" >"$tmp/nogit.out" 2>&1
rc=$?
set -e
if [ "$rc" -ne 2 ] || ! grep -q "git ls-files failed" "$tmp/nogit.out"; then
    echo "FAIL: git unable to list expected exit 2 and a message, got $rc" >&2
    cat "$tmp/nogit.out" >&2
    exit 1
fi

# a repository with no C or C++ source -> exit 1
repo="$tmp/repo"
mkdir -p "$repo"
cp "$ROOT/.clang-format" "$repo/.clang-format"
git -C "$repo" init -q
git -C "$repo" add .clang-format
set +e
(cd "$repo" && sh "$SCRIPT") >"$tmp/empty.out" 2>&1
rc=$?
set -e
if [ "$rc" -ne 1 ] || ! grep -q "git listed no C or C++ source" "$tmp/empty.out"; then
    echo "FAIL: a tree with no source expected exit 1 and a message, got $rc" >&2
    cat "$tmp/empty.out" >&2
    exit 1
fi

# only excluded sources -> exit 1
mkdir -p "$repo/sodium"
cp "$ROOT/$CLEAN" "$repo/sodium/vendored.c"
git -C "$repo" add sodium/vendored.c
set +e
(cd "$repo" && sh "$SCRIPT") >"$tmp/excluded.out" 2>&1
rc=$?
set -e
if [ "$rc" -ne 1 ] || ! grep -q "no file left to check" "$tmp/excluded.out"; then
    echo "FAIL: a tree of excluded files only expected exit 1, got $rc" >&2
    cat "$tmp/excluded.out" >&2
    exit 1
fi

# the listed generated file is exempt even when unformatted; the clean file is checked
mkdir -p "$repo/sdk"
{ echo "// Generated from the vectors harness"; cat "$ROOT/$DIRTY"; } > "$repo/sdk/rocketnet_test_vectors.h"
cp "$ROOT/$CLEAN" "$repo/sdk/clean.c"
git -C "$repo" add sdk/rocketnet_test_vectors.h sdk/clean.c
if ! (cd "$repo" && sh "$SCRIPT") >"$tmp/generated.out" 2>&1 || ! grep -qx "ok: 1 files formatted" "$tmp/generated.out"; then
    echo "FAIL: the listed generated file was not exempt, or the clean file was not counted" >&2
    cat "$tmp/generated.out" >&2
    exit 1
fi

# a file that claims to be generated but is not listed -> exit 1, named
{ echo "// Generated by hand, honestly"; cat "$ROOT/$DIRTY"; } > "$repo/sdk/claims.c"
git -C "$repo" add sdk/claims.c
set +e
(cd "$repo" && sh "$SCRIPT") >"$tmp/claims.out" 2>&1
rc=$?
set -e
if [ "$rc" -ne 1 ] || ! grep -q "^sdk/claims.c: says it is generated but is not in GENERATED" "$tmp/claims.out"; then
    echo "FAIL: an unlisted generated marker expected exit 1 naming the file, got $rc" >&2
    cat "$tmp/claims.out" >&2
    exit 1
fi

echo "ok: check_format.sh fixture checks passed"
