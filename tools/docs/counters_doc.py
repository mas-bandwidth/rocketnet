#!/usr/bin/env python3
# counters_doc.py: write the documentation-only expansion of the counter list.
#
# The counters are an X-macro table (ROCKETNET_COUNTER_ROWS in
# sdk/rocketnet_counters.h). The preprocessor drops the comments inside the
# macro, so the enum it makes carries no documentation MrDocs can attach. This
# reads the rows and writes the same anonymous enum, one enumerator per row
# in row order with its index spelled out, each with the comment the row
# carries, for the docs build only. The output is named rocketnet_counters.h
# in a directory of its own that the docs build searches before sdk/, so the
# reference names the header the counters live in; docs/mrdocs/public.cpp is its
# one includer. A #line before each enumerator points a diagnostic at the row
# it came from.
# Nothing here renames, reorders or renumbers a counter: the indices are the
# row order, as in the real enum.
#
# A row's comment: the group comment (the first comment after a blank line in
# the table) and the row's own comment (the comment directly above it), either
# or both, then the row's CLASS and FAMILY columns.
#
# usage: counters_doc.py <sdk/rocketnet_counters.h> <output rocketnet_counters.h>
import os
import re
import sys

ROW_RE = re.compile(r"^\s*X\(\s*([A-Z0-9_]+)\s*,\s*([A-Z_]+)\s*,\s*([A-Z0-9_]+)\s*\)\s*\\?\s*$")
COMMENT_RE = re.compile(r"^\s*/\*(.*)\*/\s*\\\s*$")
BLANK_RE = re.compile(r"^\s*\\\s*$")


def rows_of(header):
    with open(header, encoding="utf-8") as f:
        lines = f.read().split("\n")
    start = None
    for i, line in enumerate(lines):
        if line.startswith("#define ROCKETNET_COUNTER_ROWS("):
            start = i + 1
            break
    if start is None:
        sys.exit("error: no ROCKETNET_COUNTER_ROWS in " + header)
    rows = []
    group = None
    own = []
    after_blank = True
    for i in range(start, len(lines)):
        line = lines[i]
        m = ROW_RE.match(line)
        if m:
            text = " ".join(own) if own else None
            if group is None and text is not None and after_blank:
                group = text
            rows.append((i + 1, m.group(1), m.group(2), m.group(3), group, text))
            own = []
            after_blank = False
            if not line.rstrip().endswith("\\"):
                return rows
            continue
        m = COMMENT_RE.match(line)
        if m:
            own.append(m.group(1).strip())
            continue
        if BLANK_RE.match(line):
            group = None
            own = []
            after_blank = True
            continue
        sys.exit("error: %s:%d: a line of ROCKETNET_COUNTER_ROWS that is not a row, a comment or blank" % (header, i + 1))
    sys.exit("error: ROCKETNET_COUNTER_ROWS in %s does not end" % header)


def sentence(text):
    text = text.strip()
    if text and text[-1] not in ".:":
        text += "."
    return text


def main():
    if len(sys.argv) != 3:
        sys.exit("usage: counters_doc.py <rocketnet_counters.h> <output.h>")
    header = os.path.abspath(sys.argv[1])
    out_path = sys.argv[2]
    rows = rows_of(header)
    out = []
    out.append("// Generated by tools/docs/counters_doc.py from sdk/rocketnet_counters.h,")
    out.append("// for the documentation build only. Never included by the library.")
    out.append("// Edit the rows in sdk/rocketnet_counters.h, never this file.")
    out.append("")
    out.append("#pragma once")
    out.append("")
    out.append("/** @brief The transport counters, one per distinct reason, in index order.")
    out.append(" * The rows of ROCKETNET_COUNTER_ROWS in sdk/rocketnet_counters.h; the indices")
    out.append(" * are a contract and new counters append. A counter's CLASS is what a clean")
    out.append(" * run shows of it (REFUSAL, EXPECTED, PATH_LOSS or ARRIVAL); its FAMILY is the")
    out.append(" * RECEIVED counter its outcomes sum into, or NONE. */")
    out.append("enum")
    out.append("{")
    for index, (lineno, name, klass, family, group, own) in enumerate(rows):
        parts = []
        if group:
            parts.append(sentence(group))
        if own and own != group:
            parts.append(sentence(own))
        parts.append("Class %s, family %s." % (klass, family))
        out.append('#line %d "%s"' % (lineno, header))
        out.append("    ROCKETNET_COUNTER_%s = %d, ///< %s" % (name, index, " ".join(parts)))
    out.append('#line %d "%s"' % (rows[-1][0], header))
    out.append("    ROCKETNET_NUM_COUNTERS = %d ///< the number of counters" % len(rows))
    out.append("};")
    out.append("")
    os.makedirs(os.path.dirname(os.path.abspath(out_path)), exist_ok=True)
    with open(out_path, "w", encoding="utf-8") as f:
        f.write("\n".join(out))


if __name__ == "__main__":
    main()
