#!/usr/bin/env python3
"""Generate the vendored tlsf section of sdk/rocketnet_allocator.cpp.

The section is upstream tlsf (Matthew Conte, BSD-3-Clause) at one pinned
commit, transformed by the rules below and nothing else, so it never takes a
hand edit: change this script and run it again (tlsf/README.md).

  python3 tools/generate_tlsf.py --fetch            write the section
  python3 tools/generate_tlsf.py --fetch --check    refuse a section that differs

Ordinary builds compile the committed section and need neither this script
nor the network.
"""
import argparse
import hashlib
import re
import sys
import urllib.request
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
TARGET = ROOT / 'sdk' / 'rocketnet_allocator.cpp'
DEFAULT_INPUTS = ROOT / 'build' / 'vendor-inputs' / 'tlsf'

UPSTREAM = 'https://github.com/mattconte/tlsf'
COMMIT = 'deff9ab509341f264addbd3c8ada533678591905'
INPUTS = {
    'tlsf.c': '2a0f8cfc9cfe6114ccdc6cf22339059440b16f1149b5107bead4ae4c3a0d50e2',
    'tlsf.h': 'f7f73c48810ba60203095667c226e5a600a6ea0f69afba48efff6efbaa628d4f',
}

BEGIN = '// BEGIN VENDORED TLSF: generated by tools/generate_tlsf.py, do not edit'
END = '// END VENDORED TLSF'

# Every name the upstream code declares at file scope (every tlsf and _tlsf
# name, and the four below), renamed into RocketNet's prefix in code only (never inside comments or strings), so the
# section cannot collide with an application's own tlsf. The section is also
# wrapped in namespace rocketnet_tlsf, so its internal types (block_header_t,
# control_t, integrity_t) are RocketNet's own too.
WORD_RENAMES = {
    'pool_t': 'rocketnet_tlsf_pool_t',
    'test_ffs_fls': 'rocketnet_tlsf_test_ffs_fls',
    'TLSF_64BIT': 'ROCKETNET_TLSF_64BIT',
    'INCLUDED_tlsf': 'ROCKETNET_INCLUDED_TLSF',
    'printf': 'rocketnet_tlsf_printf',
}

# Warning adaptations (tlsf/README.md, "Warning adaptations"). The SDK builds
# this section with warnings as errors at -Wall -Wextra -Wpedantic (GCC,
# Clang) and /W4 (MSVC), as C++. Each replacement must match exactly once in
# the renamed text and changes no arithmetic.
ADAPTATIONS = [
    # One pool holds a whole heap, a server's included: the first level
    # reaches 2^38 bytes (upstream's own TODO: "We can increase this to
    # support larger sizes"). FL_INDEX_COUNT is then 31, so every first-level
    # index and its + 1 still shift an unsigned int by at most 31.
    ('\tFL_INDEX_MAX = 32,\n#else', '\tFL_INDEX_MAX = 38,\n#else'),
    # -Wsign-conversion: the builtin takes an int; the same bits (these
    # three precede rocketnet_tlsf_cast, so they cast as upstream does there)
    ('\treturn __builtin_ffs(word) - 1;',
     '\treturn __builtin_ffs((int)word) - 1;'),
    # -Wsign-conversion: fls takes an unsigned int; the same bits
    ('\t\tbits = 32 + rocketnet_tlsf_fls(high);',
     '\t\tbits = 32 + rocketnet_tlsf_fls((unsigned int)high);'),
    ('\t\tbits = rocketnet_tlsf_fls((int)size & 0xffffffff);',
     '\t\tbits = rocketnet_tlsf_fls((unsigned int)(size & 0xffffffff));'),
    # -Wcast-qual: the header and the user pointer are a fixed offset apart;
    # the offset is applied to the address as an integer, so no cast drops a
    # const qualifier
    ('\treturn rocketnet_tlsf_cast(block_header_t*,\n\t\trocketnet_tlsf_cast(unsigned char*, ptr) - block_start_offset);',
     '\treturn rocketnet_tlsf_cast(block_header_t*,\n\t\trocketnet_tlsf_cast(size_t, rocketnet_tlsf_cast(rocketnet_tlsfptr_t, ptr)) - block_start_offset);'),
    ('\treturn rocketnet_tlsf_cast(void*,\n\t\trocketnet_tlsf_cast(unsigned char*, block) + block_start_offset);',
     '\treturn rocketnet_tlsf_cast(void*,\n\t\trocketnet_tlsf_cast(size_t, rocketnet_tlsf_cast(rocketnet_tlsfptr_t, block)) + block_start_offset);'),
    # -Wsign-conversion: an address plus a size_t offset is size_t
    # arithmetic, as upstream's own implicit conversion made it, a negative
    # offset included (it wraps to the same address)
    ('\treturn rocketnet_tlsf_cast(block_header_t*, rocketnet_tlsf_cast(rocketnet_tlsfptr_t, ptr) + size);',
     '\treturn rocketnet_tlsf_cast(block_header_t*, rocketnet_tlsf_cast(size_t, rocketnet_tlsf_cast(rocketnet_tlsfptr_t, ptr)) + size);'),
    ('\tconst rocketnet_tlsfptr_t aligned =\n\t\t(rocketnet_tlsf_cast(rocketnet_tlsfptr_t, ptr) + (align - 1)) & ~(align - 1);',
     '\tconst rocketnet_tlsfptr_t aligned = rocketnet_tlsf_cast(rocketnet_tlsfptr_t,\n\t\t(rocketnet_tlsf_cast(size_t, rocketnet_tlsf_cast(rocketnet_tlsfptr_t, ptr)) + (align - 1)) & ~(align - 1));'),
    ('\t\t\tconst void* next_aligned = rocketnet_tlsf_cast(void*,\n\t\t\t\trocketnet_tlsf_cast(rocketnet_tlsfptr_t, aligned) + offset);',
     '\t\t\tconst void* next_aligned = rocketnet_tlsf_cast(void*,\n\t\t\t\trocketnet_tlsf_cast(size_t, rocketnet_tlsf_cast(rocketnet_tlsfptr_t, aligned)) + offset);'),
    ('\t\toffset_to_block(pool, -(int)block_header_overhead);',
     '\t\toffset_to_block(pool, rocketnet_tlsf_cast(size_t, -(int)block_header_overhead));'),
    ('\tblock = offset_to_block(mem, -(rocketnet_tlsfptr_t)block_header_overhead);',
     '\tblock = offset_to_block(mem, rocketnet_tlsf_cast(size_t, -(rocketnet_tlsfptr_t)block_header_overhead));'),
    ('\tblock_header_t* block = offset_to_block(pool, -(int)block_header_overhead);',
     '\tblock_header_t* block = offset_to_block(pool, rocketnet_tlsf_cast(size_t, -(int)block_header_overhead));'),
    # -Wsign-conversion: the rounding mask is a size_t
    ('\t\tconst size_t round = (1 << (rocketnet_tlsf_fls_sizet(size) - SL_INDEX_COUNT_LOG2)) - 1;',
     '\t\tconst size_t round = rocketnet_tlsf_cast(size_t, (1 << (rocketnet_tlsf_fls_sizet(size) - SL_INDEX_COUNT_LOG2)) - 1);'),
    # -Wsign-conversion: the integrity check's bitmap words, the same bits
    ('\t\t\tconst int fl_map = control->fl_bitmap & (1U << i);\n\t\t\tconst int sl_list = control->sl_bitmap[i];\n\t\t\tconst int sl_map = sl_list & (1U << j);',
     '\t\t\tconst int fl_map = rocketnet_tlsf_cast(int, control->fl_bitmap & (1U << i));\n\t\t\tconst int sl_list = rocketnet_tlsf_cast(int, control->sl_bitmap[i]);\n\t\t\tconst int sl_map = rocketnet_tlsf_cast(int, rocketnet_tlsf_cast(unsigned int, sl_list) & (1U << j));'),
    # -Wformat-pedantic: %p takes a void pointer
    ('(unsigned int)size, block_from_ptr(ptr));',
     '(unsigned int)size, rocketnet_tlsf_cast(void*, block_from_ptr(ptr)));'),
]


def sha256(data):
    return hashlib.sha256(data).hexdigest()


def read_inputs(directory, fetch):
    texts = {}
    for name, digest in INPUTS.items():
        path = directory / name
        if not path.exists():
            if not fetch:
                sys.exit(f'generate_tlsf: {path} is missing; pass --fetch')
            directory.mkdir(parents=True, exist_ok=True)
            url = f'https://raw.githubusercontent.com/mattconte/tlsf/{COMMIT}/{name}'
            with urllib.request.urlopen(url, timeout=60) as response:
                path.write_bytes(response.read())
        data = path.read_bytes()
        if sha256(data) != digest:
            sys.exit(f'generate_tlsf: {name} sha256 {sha256(data)} is not the pinned {digest}')
        texts[name] = data.decode('utf-8').replace('\r\n', '\n')
    return texts


def code_spans(text):
    """Yield (is_code, piece) over text, splitting out comments and strings."""
    i = 0
    n = len(text)
    start = 0
    while i < n:
        c = text[i]
        if text.startswith('/*', i):
            if start < i:
                yield True, text[start:i]
            j = text.find('*/', i + 2)
            j = n if j < 0 else j + 2
            yield False, text[i:j]
            i = start = j
        elif text.startswith('//', i):
            if start < i:
                yield True, text[start:i]
            j = text.find('\n', i)
            j = n if j < 0 else j
            yield False, text[i:j]
            i = start = j
        elif c == '"' or c == "'":
            if start < i:
                yield True, text[start:i]
            j = i + 1
            while j < n and text[j] != c:
                j += 2 if text[j] == '\\' else 1
            j = min(j + 1, n)
            yield False, text[i:j]
            i = start = j
        else:
            i += 1
    if start < n:
        yield True, text[start:]


def rename(text):
    out = []
    for is_code, piece in code_spans(text):
        if is_code:
            piece = re.sub(r'\b_tlsf', 'rocketnet_tlsf', piece)
            piece = re.sub(r'\btlsf', 'rocketnet_tlsf', piece)
            for old, new in WORD_RENAMES.items():
                piece = re.sub(r'\b' + re.escape(old) + r'\b', new, piece)
        out.append(piece)
    return ''.join(out)


def replace_once(text, old, new, what):
    count = text.count(old)
    if count != 1:
        sys.exit(f'generate_tlsf: {what}: expected one match, found {count}: {old!r}')
    return text.replace(old, new)


def generate(texts):
    header = texts['tlsf.h']
    source = texts['tlsf.c']

    # the header joins the source in place of its include: its guard, its
    # one system include and its extern "C" block go, since the section is
    # C++ in a namespace of its own
    header = replace_once(header, '#ifndef INCLUDED_tlsf\n#define INCLUDED_tlsf\n', '', 'header guard')
    header = replace_once(header, '#include <stddef.h>\n', '', 'header include')
    header = replace_once(header, '#if defined(__cplusplus)\nextern "C" {\n#endif\n', '', 'extern C open')
    header = replace_once(header, '#if defined(__cplusplus)\n};\n#endif\n', '', 'extern C close')
    header = replace_once(header, '\n#endif\n', '\n', 'header guard end')

    # the system includes go above the namespace: the six at the top as they
    # are, and each compiler intrinsics include under the condition of the
    # #elif that selects it, so the namespace never wraps a system header
    includes = []
    for match in re.finditer(r'^#include <[^>]+>\n', source, re.M):
        line = match.group(0)
        before = source[:match.start()].split('\n')
        branch = next((b for b in reversed(before) if b.startswith('#')), '')
        if branch.startswith('#elif '):
            includes.append('#if ' + branch[len('#elif '):] + '\n' + line + '#endif\n')
        else:
            includes.append(line)
    for match in re.findall(r'^#include <[^>]+>\n', source, re.M):
        source = replace_once(source, match, '', 'source include')
    source = replace_once(source, '#include "tlsf.h"\n', header, 'header include in source')

    body = rename(source)
    for old, new in ADAPTATIONS:
        body = replace_once(body, old, new, 'adaptation')
    # -Wundef: the two _DEBUG tests name a macro only MSVC's debug runtime
    # defines; the same test, defined first
    if body.count('#if _DEBUG\n') != 2:
        sys.exit('generate_tlsf: expected two #if _DEBUG lines')
    body = body.replace('#if _DEBUG\n', '#if defined (_DEBUG) && _DEBUG\n')

    lines = [
        BEGIN,
        f'// upstream {UPSTREAM} at {COMMIT} (tlsf 3.1), tlsf.c and tlsf.h',
        '// clang-format off',
    ]
    lines += [include.rstrip('\n') for include in includes]
    lines += [
        '',
        'namespace rocketnet_tlsf',
        '{',
        '',
    ]
    text = '\n'.join(lines) + '\n' + body.rstrip('\n') + '\n\n} // namespace rocketnet_tlsf\n// clang-format on\n' + END
    return text


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument('--inputs', type=Path, default=DEFAULT_INPUTS, help='where the pinned inputs are, or are fetched to')
    parser.add_argument('--fetch', action='store_true', help='fetch missing pinned inputs over HTTPS')
    parser.add_argument('--check', action='store_true', help='refuse a committed section that differs from the generated one')
    args = parser.parse_args()

    section = generate(read_inputs(args.inputs, args.fetch))
    target = TARGET.read_text()
    begin = target.find(BEGIN)
    end = target.find(END)
    if begin < 0 or end < begin:
        sys.exit(f'generate_tlsf: {TARGET} has no {BEGIN!r} ... {END!r} section')
    updated = target[:begin] + section + target[end + len(END):]

    if args.check:
        if updated != target:
            sys.exit('generate_tlsf: the vendored tlsf section differs from the generated one; run tools/generate_tlsf.py --fetch')
        print('generate_tlsf: the vendored tlsf section is current')
        return
    TARGET.write_text(updated)
    print(f'generate_tlsf: wrote the vendored tlsf section of {TARGET.relative_to(ROOT)}')


if __name__ == '__main__':
    main()
