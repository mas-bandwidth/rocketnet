#!/usr/bin/env python3
"""Check that every tracked .h file is classified and repository-owned headers obey guard style.

Every tracked .h in the repository must be classified into either:
  - OWNED_GLOBS: repository-owned headers across bench, examples, functional,
    fuzz, proofs, sdk, tests, and tools.
  - EXCLUDED_HEADERS: vendored or mirrored kernel/BPF headers with explicit
    provenance. The excluded files are sodium/sodium.h,
    tests/xdp_host/bpf/bpf_helpers.h, tests/xdp_host/linux/bpf.h,
    tests/xdp_host/linux/if_ether.h, tests/xdp_host/linux/if_packet.h,
    tests/xdp_host/linux/if_vlan.h, tests/xdp_host/linux/in.h,
    tests/xdp_host/linux/ip.h, tests/xdp_host/linux/ipv6.h, and
    tests/xdp_host/linux/udp.h. tests/xdp_host/server_xdp_host.h is owned.

Every repository-owned .h file must:
  1. Begin with `#pragma once` as its first preprocessing directive, with no
     code tokens before it (comments only).
  2. Immediately follow `#pragma once` (allowing only whitespace and comments,
     such as file-level doc comments) with the outer `#ifndef <GUARD>` and
     `#define <GUARD>` pair.
  3. Use the unique deterministic path-derived guard name
     `ROCKETNET_<PATH_UPPER_ALNUM_UNDERSCORE>` (except `sdk/rocketnet.h`, which
     keeps its canonical public guard `ROCKETNET_H`).
  4. Surround the entire remainder of the header with that `#ifndef` block,
     closing at the final preprocessing directive `#endif // <GUARD>`, with no
     code tokens after `#endif`.
"""

import argparse
import fnmatch
from pathlib import Path
import re
import subprocess
import sys
import tempfile
import unittest

ROOT = Path(__file__).resolve().parent.parent

OWNED_GLOBS = (
    "benchmarks/*.h",
    "examples/*.h",
    "functional/*.h",
    "fuzz/*.h",
    "tests/load/load_census.h",
    "proofs/cbmc/*.h",
    "proofs/cbmc/fragment_reassembly/*.h",
    "sdk/*.h",
    "tests/*.h",
    "tools/*.h",
    "tools/differential/*.h",
    "tests/xdp_host/server_xdp_host.h",
)

EXCLUDED_HEADERS = {
    "sodium/sodium.h": (
        "vendored two-file libsodium 1.0.22 amalgam generated by tools/generate_sodium.py "
        "and checked byte-for-byte in CI"
    ),
    "tests/xdp_host/bpf/bpf_helpers.h": (
        "mirrored kernel/libbpf BPF helper header shim for host XDP filter compilation"
    ),
    "tests/xdp_host/linux/bpf.h": (
        "mirrored Linux UAPI <linux/bpf.h> header shim for host XDP filter compilation"
    ),
    "tests/xdp_host/linux/if_ether.h": (
        "mirrored Linux UAPI <linux/if_ether.h> header shim for host XDP filter compilation"
    ),
    "tests/xdp_host/linux/if_packet.h": (
        "mirrored Linux UAPI <linux/if_packet.h> header shim for host XDP filter compilation"
    ),
    "tests/xdp_host/linux/if_vlan.h": (
        "mirrored Linux UAPI <linux/if_vlan.h> header shim for host XDP filter compilation"
    ),
    "tests/xdp_host/linux/in.h": (
        "mirrored Linux UAPI <linux/in.h> header shim for host XDP filter compilation"
    ),
    "tests/xdp_host/linux/ip.h": (
        "mirrored Linux UAPI <linux/ip.h> header shim for host XDP filter compilation"
    ),
    "tests/xdp_host/linux/ipv6.h": (
        "mirrored Linux UAPI <linux/ipv6.h> header shim for host XDP filter compilation"
    ),
    "tests/xdp_host/linux/udp.h": (
        "mirrored Linux UAPI <linux/udp.h> header shim for host XDP filter compilation"
    ),
}

RAW_STRING_START_RE = re.compile(r'(?:u8|u|U|L)?R"([^ ()\\\t\r\n]{0,16})\(')
IF_DIRECTIVE_RE = re.compile(r"^#\s*(if|ifdef|ifndef)\b")
ENDIF_DIRECTIVE_RE = re.compile(r"^#\s*endif\b")


def expected_guard(rel_path: str) -> str:
    if rel_path == "sdk/rocketnet.h":
        return "ROCKETNET_H"
    sanitized = re.sub(r"[^A-Za-z0-9]", "_", rel_path).upper()
    return f"ROCKETNET_{sanitized}"


def _glob_matches(rel_path: str, pattern: str) -> bool:
    path_parts = rel_path.split("/")
    pat_parts = pattern.split("/")
    if len(path_parts) != len(pat_parts):
        return False
    return all(fnmatch.fnmatchcase(p, pat) for p, pat in zip(path_parts, pat_parts))


def is_owned_path(rel_path: str) -> bool:
    return any(_glob_matches(rel_path, pattern) for pattern in OWNED_GLOBS)


def tracked_headers(root: Path):
    out = subprocess.check_output(
        ["git", "-C", str(root), "ls-files", "*.h"],
        text=True,
    )
    return sorted(line for line in out.splitlines() if line)


def strip_comments_and_literals(text: str) -> str:
    """Replace comments and string/char literals with spaces, preserving newlines."""
    output = list(text)

    def blank(start: int, end: int):
        for idx in range(start, end):
            if output[idx] != "\n":
                output[idx] = " "

    index = 0
    length = len(text)
    while index < length:
        raw = RAW_STRING_START_RE.match(text, index)
        if raw:
            terminator = ")" + raw.group(1) + '"'
            end = text.find(terminator, raw.end())
            end = length if end < 0 else end + len(terminator)
            blank(index, end)
            index = end
            continue
        if text.startswith("//", index):
            end = text.find("\n", index)
            end = length if end < 0 else end
            blank(index, end)
            index = end
            continue
        if text.startswith("/*", index):
            end = text.find("*/", index + 2)
            end = length if end < 0 else end + 2
            blank(index, end)
            index = end
            continue
        if text[index] in ('"', "'"):
            quote = text[index]
            end = index + 1
            while end < length:
                if text[end] == "\\":
                    end += 2
                    continue
                if text[end] == quote:
                    end += 1
                    break
                end += 1
            blank(index, end)
            index = end
            continue
        index += 1
    return "".join(output)


def parse_logical_lines(masked_text: str, raw_text: str):
    """Yield (start_line_1based, end_line_1based, masked_joined, raw_joined) handling backslash continuations."""
    masked_lines = masked_text.splitlines()
    raw_lines = raw_text.splitlines()
    n = len(raw_lines)
    i = 0
    while i < n:
        start = i + 1
        m_parts = []
        r_parts = []
        while i < n:
            r_line = raw_lines[i]
            m_line = masked_lines[i] if i < len(masked_lines) else ""
            if r_line.endswith("\\"):
                m_parts.append(m_line[:-1] if m_line.endswith("\\") else m_line)
                r_parts.append(r_line[:-1])
                i += 1
            else:
                m_parts.append(m_line)
                r_parts.append(r_line)
                i += 1
                break
        end = i
        yield start, end, " ".join(m_parts), "\n".join(r_parts)


def check_header_text(rel_path: str, text: str) -> list:
    errors = []
    guard = expected_guard(rel_path)
    masked = strip_comments_and_literals(text)
    logical = list(parse_logical_lines(masked, text))

    non_empty = [
        (idx, start, end, m.strip(), r)
        for idx, (start, end, m, r) in enumerate(logical)
        if m.strip()
    ]

    if not non_empty:
        return [f"{rel_path}:1: header has no preprocessing directives or tokens"]

    # 1. First non-empty token/directive must be `#pragma once`.
    _, p_line, _, p_masked, _ = non_empty[0]
    if not p_masked.startswith("#"):
        errors.append(f"{rel_path}:{p_line}: code tokens appear before #pragma once")
        return errors
    if re.sub(r"\s+", " ", p_masked) != "#pragma once":
        errors.append(
            f"{rel_path}:{p_line}: first directive must be '#pragma once', got '{p_masked}'"
        )
        return errors

    # 2. Second non-empty item must be `#ifndef <guard>`.
    if len(non_empty) < 4:
        errors.append(
            f"{rel_path}:{p_line}: missing '#ifndef {guard}', '#define {guard}', or '#endif // {guard}'"
        )
        return errors

    _, ifndef_line, _, ifndef_masked, _ = non_empty[1]
    if not ifndef_masked.startswith("#"):
        errors.append(
            f"{rel_path}:{ifndef_line}: code tokens appear between #pragma once and #ifndef {guard}"
        )
        return errors
    if re.sub(r"\s+", " ", ifndef_masked) != f"#ifndef {guard}":
        errors.append(
            f"{rel_path}:{ifndef_line}: expected '#ifndef {guard}', got '{ifndef_masked}'"
        )
        return errors

    # 3. Third non-empty item must be `#define <guard>` on the next line.
    _, define_line, _, define_masked, _ = non_empty[2]
    if re.sub(r"\s+", " ", define_masked) != f"#define {guard}":
        errors.append(
            f"{rel_path}:{define_line}: expected '#define {guard}' immediately after '#ifndef {guard}', got '{define_masked}'"
        )
        return errors

    # 4. Walk conditional depth across all directives from `#ifndef <guard>` to the end.
    depth = 0
    closed_at_item = None
    for item_idx in range(1, len(non_empty)):
        _, line_no, _, m_str, r_str = non_empty[item_idx]
        if not m_str.startswith("#"):
            if depth == 0:
                errors.append(
                    f"{rel_path}:{line_no}: tokens appear outside the '#ifndef {guard}' guard"
                )
                return errors
            continue

        # Check for duplicate `#pragma once`
        if item_idx > 0 and re.sub(r"\s+", " ", m_str) == "#pragma once":
            errors.append(f"{rel_path}:{line_no}: duplicate '#pragma once'")
            return errors

        if IF_DIRECTIVE_RE.match(m_str):
            if depth == 0 and item_idx > 1:
                errors.append(
                    f"{rel_path}:{line_no}: directive appears after '#ifndef {guard}' closed"
                )
                return errors
            depth += 1
        elif ENDIF_DIRECTIVE_RE.match(m_str):
            depth -= 1
            if depth < 0:
                errors.append(f"{rel_path}:{line_no}: unmatched '#endif'")
                return errors
            if depth == 0:
                closed_at_item = item_idx
                if item_idx != len(non_empty) - 1:
                    next_line = non_empty[item_idx + 1][1]
                    errors.append(
                        f"{rel_path}:{next_line}: tokens or directives appear after closing '#endif // {guard}' at line {line_no}"
                    )
                    return errors

    if depth != 0 or closed_at_item is None:
        errors.append(f"{rel_path}:{ifndef_line}: unclosed '#ifndef {guard}' (depth={depth})")
        return errors

    # 5. Verify the closing `#endif` line has no extra code tokens and has exact comment `// <guard>`.
    _, endif_line, _, endif_masked, endif_raw = non_empty[-1]
    if re.sub(r"\s+", " ", endif_masked) != "#endif":
        errors.append(
            f"{rel_path}:{endif_line}: extra tokens on closing '#endif' line: '{endif_masked}'"
        )
        return errors
    if endif_raw.strip() != f"#endif // {guard}":
        errors.append(
            f"{rel_path}:{endif_line}: closing '#endif' must be '#endif // {guard}', got '{endif_raw.strip()}'"
        )
        return errors

    return errors


def check_repository(root: Path, headers=None) -> list:
    if headers is None:
        headers = tracked_headers(root)

    errors = []
    seen_guards = {}

    for rel_path in headers:
        owned = is_owned_path(rel_path)
        excluded = rel_path in EXCLUDED_HEADERS
        if owned and excluded:
            errors.append(f"{rel_path}:1: header matches both owned globs and EXCLUDED_HEADERS")
            continue
        if not owned and not excluded:
            errors.append(
                f"{rel_path}:1: tracked header is unclassified (neither in OWNED_GLOBS nor EXCLUDED_HEADERS)"
            )
            continue
        if excluded:
            if not (root / rel_path).is_file():
                errors.append(f"{rel_path}:1: excluded header does not exist on disk")
            continue

        full_path = root / rel_path
        if not full_path.is_file():
            errors.append(f"{rel_path}:1: tracked owned header does not exist on disk")
            continue

        guard = expected_guard(rel_path)
        if guard in seen_guards:
            errors.append(
                f"{rel_path}:1: guard collision on '{guard}' with '{seen_guards[guard]}'"
            )
            continue
        seen_guards[guard] = rel_path

        text = full_path.read_text(encoding="utf-8")
        errors.extend(check_header_text(rel_path, text))

    # Ensure every entry in EXCLUDED_HEADERS is still present in the tracked list when checking full repo.
    header_set = set(headers)
    for ex_path, reason in sorted(EXCLUDED_HEADERS.items()):
        if not reason.strip():
            errors.append(f"{ex_path}:1: excluded header has empty provenance reason")
        if ex_path not in header_set and (root / ex_path).exists():
            errors.append(f"{ex_path}:1: excluded header is not in tracked header list")

    return errors


class HeaderGuardCheckTests(unittest.TestCase):
    def test_valid_owned_header_passes(self):
        valid = (
            "/* License comment */\n\n"
            "#pragma once\n\n"
            "#ifndef ROCKETNET_SDK_ROCKETNET_EXAMPLE_H\n"
            "#define ROCKETNET_SDK_ROCKETNET_EXAMPLE_H\n\n"
            "int example_fn( void );\n\n"
            "#endif // ROCKETNET_SDK_ROCKETNET_EXAMPLE_H\n"
        )
        self.assertEqual(check_header_text("sdk/rocketnet_example.h", valid), [])

    def test_public_header_canonical_guard_passes(self):
        valid = (
            "/* License comment */\n\n"
            "#pragma once\n\n"
            "/// Doc comment between pragma once and ifndef.\n\n"
            "#ifndef ROCKETNET_H\n"
            "#define ROCKETNET_H\n\n"
            "int rocketnet_fn( void );\n\n"
            "#endif // ROCKETNET_H\n"
        )
        self.assertEqual(check_header_text("sdk/rocketnet.h", valid), [])

    def test_missing_pragma_once_fails(self):
        bad = (
            "#ifndef ROCKETNET_SDK_ROCKETNET_EXAMPLE_H\n"
            "#define ROCKETNET_SDK_ROCKETNET_EXAMPLE_H\n"
            "int x;\n"
            "#endif // ROCKETNET_SDK_ROCKETNET_EXAMPLE_H\n"
        )
        errs = check_header_text("sdk/rocketnet_example.h", bad)
        self.assertEqual(len(errs), 1)
        self.assertIn("first directive must be '#pragma once'", errs[0])

    def test_tokens_before_pragma_once_fails(self):
        bad = (
            "extern int pre_token;\n"
            "#pragma once\n"
            "#ifndef ROCKETNET_SDK_ROCKETNET_EXAMPLE_H\n"
            "#define ROCKETNET_SDK_ROCKETNET_EXAMPLE_H\n"
            "#endif // ROCKETNET_SDK_ROCKETNET_EXAMPLE_H\n"
        )
        errs = check_header_text("sdk/rocketnet_example.h", bad)
        self.assertEqual(len(errs), 1)
        self.assertIn("code tokens appear before #pragma once", errs[0])

    def test_wrong_guard_name_fails(self):
        bad = (
            "#pragma once\n"
            "#ifndef ROCKETNET_EXAMPLE_H\n"
            "#define ROCKETNET_EXAMPLE_H\n"
            "#endif // ROCKETNET_EXAMPLE_H\n"
        )
        errs = check_header_text("sdk/rocketnet_example.h", bad)
        self.assertEqual(len(errs), 1)
        self.assertIn("expected '#ifndef ROCKETNET_SDK_ROCKETNET_EXAMPLE_H'", errs[0])

    def test_mismatched_define_fails(self):
        bad = (
            "#pragma once\n"
            "#ifndef ROCKETNET_SDK_ROCKETNET_EXAMPLE_H\n"
            "#define ROCKETNET_WRONG_H\n"
            "#endif // ROCKETNET_SDK_ROCKETNET_EXAMPLE_H\n"
        )
        errs = check_header_text("sdk/rocketnet_example.h", bad)
        self.assertEqual(len(errs), 1)
        self.assertIn("expected '#define ROCKETNET_SDK_ROCKETNET_EXAMPLE_H'", errs[0])

    def test_wrong_endif_comment_fails(self):
        bad = (
            "#pragma once\n"
            "#ifndef ROCKETNET_SDK_ROCKETNET_EXAMPLE_H\n"
            "#define ROCKETNET_SDK_ROCKETNET_EXAMPLE_H\n"
            "int x;\n"
            "#endif // #ifndef ROCKETNET_SDK_ROCKETNET_EXAMPLE_H\n"
        )
        errs = check_header_text("sdk/rocketnet_example.h", bad)
        self.assertEqual(len(errs), 1)
        self.assertIn("closing '#endif' must be '#endif // ROCKETNET_SDK_ROCKETNET_EXAMPLE_H'", errs[0])

    def test_tokens_after_closing_endif_fails(self):
        bad = (
            "#pragma once\n"
            "#ifndef ROCKETNET_SDK_ROCKETNET_EXAMPLE_H\n"
            "#define ROCKETNET_SDK_ROCKETNET_EXAMPLE_H\n"
            "int x;\n"
            "#endif // ROCKETNET_SDK_ROCKETNET_EXAMPLE_H\n"
            "int trailing_decl;\n"
        )
        errs = check_header_text("sdk/rocketnet_example.h", bad)
        self.assertEqual(len(errs), 1)
        self.assertIn("tokens or directives appear after closing", errs[0])

    def test_directive_inside_comment_or_string_is_ignored(self):
        valid = (
            "/*\n"
            "#ifndef FAKE_GUARD_IN_COMMENT\n"
            "#endif\n"
            "*/\n"
            "#pragma once\n\n"
            "#ifndef ROCKETNET_SDK_ROCKETNET_EXAMPLE_H\n"
            "#define ROCKETNET_SDK_ROCKETNET_EXAMPLE_H\n\n"
            'const char * s = "#endif /* not a directive */";\n\n'
            "#endif // ROCKETNET_SDK_ROCKETNET_EXAMPLE_H\n"
        )
        self.assertEqual(check_header_text("sdk/rocketnet_example.h", valid), [])

    def test_unclassified_header_fails(self):
        with tempfile.TemporaryDirectory() as tmp:
            root = Path(tmp)
            (root / "mystery").mkdir()
            (root / "mystery" / "unclassified.h").write_text("#pragma once\n", encoding="utf-8")
            errs = check_repository(root, ["mystery/unclassified.h"])
            self.assertEqual(len(errs), 1)
            self.assertIn("tracked header is unclassified", errs[0])

    def test_guard_collision_fails(self):
        with tempfile.TemporaryDirectory() as tmp:
            root = Path(tmp)
            (root / "sdk").mkdir()
            for name in ("a-b.h", "a_b.h"):
                (root / "sdk" / name).write_text(
                    "#pragma once\n"
                    "#ifndef ROCKETNET_SDK_A_B_H\n"
                    "#define ROCKETNET_SDK_A_B_H\n"
                    "#endif // ROCKETNET_SDK_A_B_H\n",
                    encoding="utf-8",
                )
            errs = check_repository(root, ["sdk/a-b.h", "sdk/a_b.h"])
            self.assertEqual(len(errs), 1)
            self.assertIn("guard collision on 'ROCKETNET_SDK_A_B_H'", errs[0])

    def test_repository_is_clean(self):
        self.assertEqual(check_repository(ROOT), [])


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--self-test",
        action="store_true",
        help="run unit self-tests for the header guard checker",
    )
    args, remaining = parser.parse_known_args()
    if args.self_test:
        suite = unittest.defaultTestLoader.loadTestsFromTestCase(HeaderGuardCheckTests)
        runner = unittest.TextTestRunner(verbosity=2 if "-v" in remaining else 1)
        result = runner.run(suite)
        return 0 if result.wasSuccessful() else 1

    headers = tracked_headers(ROOT)
    errors = check_repository(ROOT, headers)
    if errors:
        for err in errors:
            print(f"FAIL: {err}", file=sys.stderr)
        return 1

    owned_count = sum(1 for h in headers if is_owned_path(h))
    excluded_count = sum(1 for h in headers if h in EXCLUDED_HEADERS)
    print(
        f"Header guards clean: {owned_count} owned headers verified, "
        f"{excluded_count} excluded headers accounted for ({len(headers)} total tracked .h files)"
    )
    for ex_path in sorted(EXCLUDED_HEADERS):
        print(f"excluded: {ex_path}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
