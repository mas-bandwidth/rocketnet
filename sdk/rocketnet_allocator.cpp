// the largest one request: tlsf's size-class rounding shifts an int by the
// request's top bit less five, so a request stays below 2^35

#define ROCKETNET_HEAP_MAX_REQUEST_BYTES ( (uint64_t) 1 << 34 )

struct rocketnet_heap_t
{
    rocketnet_tlsf::rocketnet_tlsf_t tlsf;
    rocketnet_tlsf::rocketnet_tlsf_pool_t pool;
    uint64_t live_allocations;
    uint64_t live_bytes;
    uint64_t peak_bytes;
    uint64_t refusals;
#if ROCKETNET_TEST_SEAMS
    uint64_t refuse_countdown;                          // rocketnet_heap_refuse_allocation_for_test; 0 is none
#endif // #if ROCKETNET_TEST_SEAMS
};

static uint64_t rocketnet_heap_header_bytes()
{
    return rn_align64( sizeof( rocketnet_heap_t ) ) + rn_align64( rocketnet_tlsf::rocketnet_tlsf_size() );
}

uint64_t rocketnet_heap_required_bytes( uint64_t planned_bytes )
{
    // the plan, plus tlsf's rounding of a request up to its size class (at
    // most a 32nd of it, and the largest request is at most the plan), plus
    // the pool's two sentinel headers and an alignment's slack

    if ( planned_bytes == 0 || planned_bytes > ROCKETNET_HEAP_MAX_REQUEST_BYTES * 8 )
        return 0;

    const uint64_t rounding = planned_bytes / 32 + ROCKETNET_ALLOCATION_ALIGNMENT;
    const uint64_t pool = planned_bytes + rounding + rocketnet_tlsf::rocketnet_tlsf_pool_overhead() + ROCKETNET_ALLOCATION_ALIGNMENT;

    return rocketnet_heap_header_bytes() + rn_align64( pool );
}

rocketnet_heap_t * rocketnet_heap_create( void * memory, uint64_t bytes )
{
    const uint64_t header = rocketnet_heap_header_bytes();

    if ( !memory || ( (uintptr_t) memory % ROCKETNET_ALLOCATION_ALIGNMENT ) != 0 || bytes <= header )
        return NULL;

    const uint64_t pool_bytes = bytes - header;
    if ( pool_bytes < rocketnet_tlsf::rocketnet_tlsf_pool_overhead() + rocketnet_tlsf::rocketnet_tlsf_block_size_min() ||
         pool_bytes > rocketnet_tlsf::rocketnet_tlsf_block_size_max() || pool_bytes > SIZE_MAX )
        return NULL;

    uint8_t * base = (uint8_t *) memory;
    rocketnet_heap_t * heap = (rocketnet_heap_t *) base;
    memset( heap, 0, sizeof( *heap ) );

    heap->tlsf = rocketnet_tlsf::rocketnet_tlsf_create( base + rn_align64( sizeof( rocketnet_heap_t ) ) );
    if ( !heap->tlsf )
        return NULL;

    heap->pool = rocketnet_tlsf::rocketnet_tlsf_add_pool( heap->tlsf, base + header, (size_t) pool_bytes );
    if ( !heap->pool )
        return NULL;

    return heap;
}

void * rocketnet_heap_malloc( rocketnet_heap_t * heap, size_t bytes )
{
    rocketnet_assert( heap );

#if ROCKETNET_TEST_SEAMS
    if ( heap->refuse_countdown > 0 && --heap->refuse_countdown == 0 )
    {
        heap->refusals++;
        return NULL;
    }
#endif // #if ROCKETNET_TEST_SEAMS

    void * p = bytes > 0 && bytes < ROCKETNET_HEAP_MAX_REQUEST_BYTES ? rocketnet_tlsf::rocketnet_tlsf_malloc( heap->tlsf, bytes ) : NULL;
    if ( !p )
    {
        heap->refusals++;
        return NULL;
    }

    heap->live_allocations++;
    heap->live_bytes += rocketnet_tlsf::rocketnet_tlsf_block_size( p );
    if ( heap->live_bytes > heap->peak_bytes )
        heap->peak_bytes = heap->live_bytes;

    return p;
}

void rocketnet_heap_free( rocketnet_heap_t * heap, void * p )
{
    rocketnet_assert( heap );

    if ( !p )
        return;

    rocketnet_assert( heap->live_allocations > 0 );
    heap->live_allocations--;
    heap->live_bytes -= rocketnet_tlsf::rocketnet_tlsf_block_size( p );
    rocketnet_tlsf::rocketnet_tlsf_free( heap->tlsf, p );
}

uint64_t rocketnet_heap_live_allocations( const rocketnet_heap_t * heap )
{
    return heap ? heap->live_allocations : 0;
}

uint64_t rocketnet_heap_refusals( const rocketnet_heap_t * heap )
{
    return heap ? heap->refusals : 0;
}

uint64_t rocketnet_heap_peak_bytes( const rocketnet_heap_t * heap )
{
    return heap ? heap->peak_bytes : 0;
}

void * rocketnet_heap_allocate( void * heap, size_t bytes )
{
    return rocketnet_heap_malloc( (rocketnet_heap_t *) heap, bytes );
}

void rocketnet_heap_release( void * heap, void * p )
{
    rocketnet_heap_free( (rocketnet_heap_t *) heap, p );
}

#if ROCKETNET_TEST_SEAMS
void rocketnet_heap_refuse_allocation_for_test( rocketnet_heap_t * heap, uint64_t nth )
{
    if ( heap )
        heap->refuse_countdown = nth;
}
#endif // #if ROCKETNET_TEST_SEAMS

bool rocketnet_heap_check( const rocketnet_heap_t * heap )
{
    return heap && rocketnet_tlsf::rocketnet_tlsf_check( heap->tlsf ) == 0 && rocketnet_tlsf::rocketnet_tlsf_check_pool( heap->pool ) == 0;
}
