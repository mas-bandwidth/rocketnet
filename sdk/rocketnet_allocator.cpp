{
    rocketnet_assert( arena );
    return arena->num_regions;
}

rn_region_t * rn_arena_region( rn_arena_t * arena, int index )
{
    rocketnet_assert( arena );

    if ( index < 0 || index >= arena->num_regions )
        return NULL;

    return &arena->regions[index];
}

