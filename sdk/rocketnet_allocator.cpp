rocketnet_tlsf_t rocketnet_tlsf_create(void* mem)
{
#if defined (_DEBUG) && _DEBUG
	if (rocketnet_tlsf_test_ffs_fls())
	{
		return 0;
	}
#endif

	if (((rocketnet_tlsfptr_t)mem % ALIGN_SIZE) != 0)
	{
		rocketnet_tlsf_printf("tlsf_create: Memory must be aligned to %u bytes.\n",
			(unsigned int)ALIGN_SIZE);
		return 0;
	}

	control_construct(rocketnet_tlsf_cast(control_t*, mem));

	return rocketnet_tlsf_cast(rocketnet_tlsf_t, mem);
}

rocketnet_tlsf_t rocketnet_tlsf_create_with_pool(void* mem, size_t bytes)
{
	rocketnet_tlsf_t rocketnet_tlsf = rocketnet_tlsf_create(mem);
	rocketnet_tlsf_add_pool(rocketnet_tlsf, (char*)mem + rocketnet_tlsf_size(), bytes - rocketnet_tlsf_size());
	return rocketnet_tlsf;
}

